// Generates the shared test vectors from the JS reference implementation:
//   node web/test/gen-vectors.mjs > firmware/test/vectors.inc          (C firmware)
//   node web/test/gen-vectors.mjs --json > desktop/internal/omnicore/testdata/vectors.json  (Go desktop app)
// CI regenerates both and fails if either differs from the committed copy.
import { Engine, gainAt, FLAG_ENABLED, FLAG_LINEAR, GAIN_ONE } from '../js/omni-core.js';
import { encodeProfile, rawAccelFit } from '../js/export.js';

const profiles = [
  { name: 'flat', gains: [1, 1, 1, 1, 1, 1, 1, 1], linear: false, smoothing: 32, rot: 0 },
  { name: 'pv8', gains: [0.92, 0.97, 1.05, 1.02, 1.08, 1.0, 0.95, 0.9], linear: false, smoothing: 32, rot: 0 },
  { name: 'pv8_linear', gains: [0.92, 0.97, 1.05, 1.02, 1.08, 1.0, 0.95, 0.9], linear: true, smoothing: 32, rot: 0 },
  { name: 'pv16_rot', gains: Array.from({ length: 16 }, (_, k) => 1 + 0.12 * Math.sin((k * Math.PI) / 4) + 0.05 * Math.cos((k * Math.PI) / 8)), linear: false, smoothing: 8, rot: 350 },
  { name: 'pv4_nosmooth', gains: [1.2, 0.8, 1.0, 1.1], linear: false, smoothing: 0, rot: -1200 },
];

const q12 = (g) => Math.round(g * GAIN_ONE);

// Deterministic pseudo-random motion: strokes in various directions with pauses.
function* motion(seed) {
  let s = seed >>> 0;
  const rnd = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 2 ** 32);
  let t = 1000;
  for (let stroke = 0; stroke < 12; stroke++) {
    const ang = rnd() * 2 * Math.PI;
    const speed = 1 + rnd() * 40;
    const len = 5 + Math.floor(rnd() * 40);
    for (let i = 0; i < len; i++) {
      const jitter = (rnd() - 0.5) * 0.6;
      const dx = Math.round(Math.cos(ang + jitter) * speed * (0.5 + rnd()));
      const dy = Math.round(-Math.sin(ang + jitter) * speed * (0.5 + rnd()));
      t += 1000;
      yield [dx, dy, t];
    }
    t += rnd() < 0.5 ? 10000 : 80000; // short pause keeps history, long pause resets
  }
}

const data = profiles.map((p, pi) => {
  const cfg = {
    flags: FLAG_ENABLED | (p.linear ? FLAG_LINEAR : 0),
    nPoints: p.gains.length,
    smoothingCounts: p.smoothing,
    resetMs: 40,
    rotationCdeg: p.rot,
    gainsQ12: p.gains.map(q12),
  };
  const eng = new Engine(cfg);
  const g = cfg.gainsQ12.map((v) => v / GAIN_ONE);
  const curve = [];
  for (let a = -45; a <= 405; a += 7.5) curve.push([a, gainAt(g, a, p.linear)]);
  const steps = [];
  for (const [dx, dy, t] of motion(pi + 7)) steps.push([dx, dy, t, ...eng.process(dx, dy, t)]);
  return { ...p, cfg, curve, steps, code: encodeProfile(cfg), rawAccel: rawAccelFit(cfg) };
});

if (process.argv.includes('--json')) {
  const out = data.map((d) => ({
    name: d.name,
    code: d.code,
    curve: d.curve,
    steps: d.steps,
    rawAccel: d.rawAccel,
  }));
  process.stdout.write(JSON.stringify(out, null, 1) + '\n');
} else {
  const lines = [];
  lines.push('// Generated by web/test/gen-vectors.mjs - do not edit.');
  lines.push(`#define VEC_PROFILE_COUNT ${data.length}`);
  data.forEach((d, pi) => {
    lines.push(`// profile ${pi}: ${d.name}`);
    lines.push(`static const uint16_t vec_gains_${pi}[] = {${d.cfg.gainsQ12.join(', ')}};`);
    lines.push(`static const float vec_curve_${pi}[][2] = {${d.curve.map(([a, v]) => `{${a.toFixed(1)}f, ${v.toFixed(7)}f}`).join(', ')}};`);
    lines.push(`static const vec_step_t vec_steps_${pi}[] = {${d.steps.map(([dx, dy, t, ox, oy]) => `{${dx}, ${dy}, ${t}u, ${ox}, ${oy}}`).join(', ')}};`);
  });
  lines.push('static const vec_profile_t vec_profiles[VEC_PROFILE_COUNT] = {');
  data.forEach((d, pi) => {
    lines.push(`  {"${d.name}", vec_gains_${pi}, ${d.gains.length}, ${d.linear ? 1 : 0}, ${d.smoothing}, ${d.rot}, ` +
      `vec_curve_${pi}, sizeof(vec_curve_${pi}) / sizeof(vec_curve_${pi}[0]), ` +
      `vec_steps_${pi}, sizeof(vec_steps_${pi}) / sizeof(vec_steps_${pi}[0])},`);
  });
  lines.push('};');
  process.stdout.write(lines.join('\n') + '\n');
}
